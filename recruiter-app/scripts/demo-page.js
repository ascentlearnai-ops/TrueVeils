const { parseHTML } = require("linkedom");

// Reuse the homepage's working preview instead of maintaining a second demo UI.
function buildDemoPage(source) {
  const { document } = parseHTML(source);
  const candidate = document.body.dataset.audience === "candidate";
  const product = document.querySelector("#product");
  if (!product) throw new Error("Homepage is missing its product preview");
  document.querySelector("main").replaceChildren(product);
  product.querySelector(".principles")?.remove();
  document.querySelectorAll('script[src="motion.js"], link[href="motion.css"]').forEach(node => node.remove());
  document.body.classList.add("demo-page");
  document.title = candidate ? "Candidate demo | Truveil Secure" : "Interactive demo | Truveil";
  const description = "Try Truveil in your browser. No account, email code, or installation required. Sample data and private, on-device text previews.";
  for (const selector of ['meta[name="description"]', 'meta[property="og:description"]'])
    document.querySelector(selector)?.setAttribute("content", description);
  document.querySelector('meta[property="og:title"]')?.setAttribute("content", document.title);
  product.querySelector(".eyebrow").textContent = "INTERACTIVE DEMO / NO SIGN-IN REQUIRED";
  const heading = document.createElement("h1");
  heading.textContent = candidate ? "The candidate experience." : "Truveil, in practice.";
  product.querySelector(".section-heading h2").replaceWith(heading);
  product.querySelector(".section-heading > p").textContent = candidate
    ? "Explore a sample transcript or practice with your own answer. No interview code, microphone access, or installation needed."
    : "Watch a sample interview or analyze your own text. No account or installation needed. Scores are advisory signals, not proof of AI use.";
  // Navigation still returns to the full site, not to missing sections here.
  document.querySelectorAll('a[href^="#"]').forEach(link => {
    if (!document.getElementById(link.getAttribute("href").slice(1)))
      link.setAttribute("href", `index.html${link.getAttribute("href")}`);
  });
  const html = document.toString().replace(/\r\n/g, "\n").replace(/[\t ]+$/gm, "").trimEnd();
  return `<!-- Generated by recruiter-app/scripts/build-website-demo.js. Edit index.html and scripts/demo-page.js. -->\n${html}\n`;
}

module.exports = { buildDemoPage };
