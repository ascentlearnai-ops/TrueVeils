const path = require("node:path");
const { existsSync, copyFileSync, readFileSync, writeFileSync } = require("node:fs");
const { buildSync } = require("esbuild");
const { buildDemoPage } = require("./demo-page");

const options = {
  entryPoints: [path.join(__dirname, "../src/website/interview-demo.js")],
  bundle: true,
  minifySyntax: true,
  treeShaking: true,
  platform: "browser",
  target: ["es2020"],
  banner: {
    js: "// Generated by recruiter-app/scripts/build-website-demo.js. Edit src/website instead.",
  },
};
buildSync({
  ...options,
  outfile: path.join(__dirname, "../../landing/interview-demo.js"),
  define: { TRUVEIL_CANDIDATE_PREVIEW: "false" },
});
writeDemoPage(path.join(__dirname, "../../landing"));

function writeDemoPage(root) {
  writeFileSync(
    path.join(root, "demo.html"),
    buildDemoPage(readFileSync(path.join(root, "index.html"), "utf8")),
  );
}

const candidateRoot = path.resolve(__dirname, "../../../Truveil-Client");
if (existsSync(path.join(candidateRoot, "index.html"))) {
  buildSync({
    ...options,
    outfile: path.join(candidateRoot, "interview-demo.js"),
    define: { TRUVEIL_CANDIDATE_PREVIEW: "true" },
  });
  copyFileSync(
    path.join(__dirname, "../../landing/interview-demo.css"),
    path.join(candidateRoot, "interview-demo.css"),
  );
  writeDemoPage(candidateRoot);
}
